"""Give every hyperlane (sea adjacency in map/adjacencies.csv) an adjacency rule: lanes are open as usual, but while an
operation runs (global flag HOD_op_active) every lane is CLOSED to everyone except the ones with BOTH ends in the
operation's theater (state flag HOD_theater, set by the operation on the theater's planets).

The engine accepts a province only once as a rule icon and only once in any rule's required_provinces, so each rule
only gets the ones no other rule (or a hand-written rule above the generated block) already uses.

It also rewrites each lane's comment from its province numbers ("Planet to Planet (states A > B)", planets being
strategic regions), since hand-written comments drift.

Run again after adding or changing hyperlanes:  python gen_hyperlanes.py [mod_folder]
Tested in game: a lane is closed while its rule's is_disabled trigger is true.
"""
import os
import sys

from hoi4_country_editor import Mod, find_mod_root, read_text, write_text

BEGIN = '# BEGIN HOD hyperlanes - generated by tools/hoi4_country_editor/gen_hyperlanes.py, do not edit by hand'
END = '# END HOD hyperlanes'


def rule(name, required, state_a, state_b, icon):
    inside = f'{state_a} = {{ has_state_flag = HOD_theater }}'
    if state_b != state_a:
        inside += f'\n\t\t\t\t{state_b} = {{ has_state_flag = HOD_theater }}'
    allow = '\t{\n\t\tarmy = yes\n\t\tnavy = yes\n\t\tsubmarine = yes\n\t\ttrade = yes\n\t}\n'
    return (f'adjacency_rule =\n{{\n\tname = "{name}"\n\n'
            + ''.join(f'\t{rel} =\n{allow}' for rel in ('contested', 'enemy', 'friend', 'neutral'))
            + (f'\n\trequired_provinces = {{ {" ".join(required)} }}\n' if required else '')
            + f'\n\tis_disabled = {{\n\t\thas_global_flag = HOD_op_active\n\t\tNOT = {{\n\t\t\tAND = {{\n\t\t\t\t{inside}\n'
            f'\t\t\t}}\n\t\t}}\n\t\ttooltip = HOD_lane_closed_tt\n\t}}\n'
            + (f'\n\ticon = {icon}\n\toffset = {{ 0 0 0 }}\n' if icon else '') + '}\n')


def planet_names(mod):
    """Province -> name of its strategic region (in this mod, a region is a planet)."""
    from hoi4_country_editor import get, parse
    out = {}
    for f in mod.files('map/strategicregions'):
        for _, reg in parse(read_text(f)):
            if isinstance(reg, list):
                name = mod.loc.get(get(reg, 'name', ''), get(reg, 'name', '?'))
                for _, p in get(reg, 'provinces', []) or []:
                    out.setdefault(p, name)
    return out


def generate(mod):
    prov_state = mod.prov_state
    planet = planet_names(mod)
    adj_path = mod.path('map', 'adjacencies.csv')
    lines = read_text(adj_path).split('\n')
    rules_path = mod.path('map', 'adjacency_rules.txt')
    text = read_text(rules_path)
    if BEGIN in text:
        text = text[:text.index(BEGIN)].rstrip('\n') + text[text.index(END) + len(END):]
    import re
    used_req = set(re.findall(r'\d+', ' '.join(re.findall(r'required_provinces\s*=\s*\{([^}]*)\}', text))))
    used_icon = set(re.findall(r'\bicon\s*=\s*(\d+)', text))
    rules, skipped = [], []
    for i, line in enumerate(lines):
        c = line.split(';')
        if len(c) < 10 or c[2] != 'sea' or not c[0].isdigit():
            continue
        sa, sb = prov_state.get(c[0]), prov_state.get(c[1])
        if not (sa and sb):  # an end that is not in any state cannot be in a theater: leave the lane as it is
            skipped.append(c[9])
            continue
        name = f'HOD_lane_{c[0]}_{c[1]}'
        c[8] = name
        c[9] = f'{planet.get(c[0], "?")} to {planet.get(c[1], "?")} (states {sa} > {sb})'.replace(';', ',')
        lines[i] = ';'.join(c)
        required = [p for p in (c[0], c[1]) if p not in used_req]
        # the lane's sea province, else one of its land ends: each province may be an icon only once
        icon = next((x for x in (c[3], c[0], c[1]) if x not in used_icon), None)
        used_req.update(required)
        used_icon.add(icon)
        rules.append(rule(name, required, sa, sb, icon))
    write_text(adj_path, '\n'.join(lines))

    text = text.rstrip('\n') + '\n\n' + BEGIN + '\n' + '\n'.join(rules) + END + '\n'
    write_text(rules_path, text)
    return len(rules), skipped


if __name__ == '__main__':
    root = sys.argv[1] if len(sys.argv) > 1 else find_mod_root()
    n, skipped = generate(Mod(root))
    print(f'{n} hyperlanes: open normally; during an operation only lanes inside its theater stay open.' + (f' Skipped (end not in a state): {skipped}' if skipped else ''))
